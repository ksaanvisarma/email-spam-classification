import kagglehub
import pandas as pd
import os
import glob

path = kagglehub.dataset_download(
    "balaka18/email-spam-classification-dataset-csv"
)

print("Path to dataset files:", path)

csv_files = glob.glob(os.path.join(path, "*.csv"))

print("CSV files found:", csv_files)

if not csv_files:
    raise FileNotFoundError("No CSV file was found in the downloaded dataset.")

df = pd.read_csv(csv_files[0], header = 0)

display(df.head())

"""Exploring the Dataset"""

print("Dataset Shape: ", df.shape)

print("First 10 column names: ")
print(df.columns[:10].tolist())

print("last 10 column names: ")
print(df.columns[-10:].tolist())

print("Data Types: ")
print(df.dtypes.value_counts())

print("Missing values: ", df.isnull().sum().sum())

print("Duplicate rows: ", df.duplicated().sum())

#Spam = 1
#Not Spam = 0
x = df.drop(columns=["Email No.", "Prediction"])
y = df["Prediction"]

print("Feature Shape: ", x.shape)
print("Target Shape: ", y.shape)

print("Target distribution: ")
print(y.value_counts())

print("Target percentages: ")
print((y.value_counts(normalize=True) * 100).round(2))

from sklearn.model_selection import train_test_split

x_train, x_test, y_train, y_test = train_test_split(
    x,
    y,
    test_size = 0.2,
    random_state = 42,
    stratify = y
)

"""Logistic Regression"""

from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_score

model = make_pipeline(
    StandardScaler(),
    LogisticRegression(max_iter=2000, random_state=42)
)

cv = StratifiedKFold(
    n_splits = 5,
    shuffle = True,
    random_state = 42
)

cv_accuracy = cross_val_score(
    model,
    x_train,
    y_train,
    cv=cv,
    scoring="accuracy"
)

cv_f1 = cross_val_score(
    model,
    x_train,
    y_train,
    cv=cv,
    scoring="f1"
)

print("Accuracy for each fold:", cv_accuracy)
print("Mean CV accuracy:", cv_accuracy.mean())
print("Mean CV F1-score:", cv_f1.mean())

from sklearn.metrics import(
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

import seaborn as sns
import matplotlib.pyplot as plt

model.fit(x_train, y_train)

y_test_pred = model.predict(x_test)

print("Final Test Accuracy: ", accuracy_score(y_test, y_test_pred))

print("Test Precision: ", precision_score(y_test, y_test_pred, zero_division=0))

print("Test Recall: ", recall_score(y_test, y_test_pred, zero_division=0))

print("Test F1_score:", f1_score(y_test, y_test_pred, zero_division=0))

print("Classification report: ", classification_report(y_test, y_test_pred, zero_division=0))

cm = confusion_matrix(y_test, y_test_pred)

sns.heatmap(cm, annot=True, fmt="d", cmap="Blues")
plt.xlabel("Predicted label")
plt.ylabel("Actual label")
plt.title("Logistic Regression - Test Confusion Matrix")
plt.show()

